let lista = []
lista.push("a")
console.log(lista)
lista.push("b")
console.log(lista)
//agregar al imicio de un arreglo un shift
lista.unshift("c")
console.log(lista)
//pop->elimina elementos al final
lista.pop()
console.log(lista)
//shift->elimina al inicio
lista.shift()
console.log(lista)